/**
 * MetaSafe Cleaning Report Generator
 * Generates downloadable reports (TXT/PDF) after cleaning
 */

/**
 * Generate cleaning report data
 * @param {Object} fileData - File data with metadata info
 * @param {Object} cleaningResult - Result of cleaning operation
 * @returns {Object} Report data
 */
function generateReportData(fileData, cleaningResult) {
  const timestamp = new Date().toISOString();
  const removedItems = [];
  
  // Collect removed metadata
  if (fileData.metadata && fileData.metadata.items) {
    fileData.metadata.items.forEach(item => {
      if (item.risk !== 'low') {
        removedItems.push({
          name: item.name,
          value: item.value ? String(item.value).substring(0, 100) : 'N/A',
          risk: item.risk
        });
      }
    });
  }
  
  return {
    timestamp,
    filename: fileData.name,
    fileType: fileData.type,
    originalSize: fileData.size,
    cleanedSize: cleaningResult?.size || fileData.size,
    riskScore: fileData.riskScore,
    gpsRemoved: !!fileData.gpsCoords,
    gpsCoords: fileData.gpsCoords,
    removedItems,
    totalRemoved: removedItems.length,
    cleaningStatus: cleaningResult?.success ? 'SUCCESS' : 'PARTIAL'
  };
}

/**
 * Generate TXT report
 * @param {Object} reportData - Report data
 * @param {string} lang - Language code
 * @returns {string} TXT content
 */
function generateTXTReport(reportData, lang = 'tr') {
  const labels = lang === 'tr' ? {
    title: 'METASAFE TEMİZLEME RAPORU',
    date: 'Tarih',
    filename: 'Dosya Adı',
    fileType: 'Dosya Türü',
    originalSize: 'Orijinal Boyut',
    cleanedSize: 'Temizlenmiş Boyut',
    riskScore: 'Risk Skoru',
    gpsRemoved: 'GPS Verisi',
    removedData: 'Kaldırılan Veriler',
    noData: 'Veri bulunamadı',
    status: 'Durum',
    success: 'BAŞARILI',
    partial: 'KISMİ',
    footer: 'Bu rapor MetaSafe tarafından otomatik oluşturuldu.',
    privacy: 'Tüm işlem tarayıcınızda gerçekleşti - hiçbir veri sunucuya gönderilmedi.'
  } : {
    title: 'METASAFE CLEANING REPORT',
    date: 'Date',
    filename: 'Filename',
    fileType: 'File Type',
    originalSize: 'Original Size',
    cleanedSize: 'Cleaned Size',
    riskScore: 'Risk Score',
    gpsRemoved: 'GPS Data',
    removedData: 'Removed Data',
    noData: 'No data found',
    status: 'Status',
    success: 'SUCCESS',
    partial: 'PARTIAL',
    footer: 'This report was automatically generated by MetaSafe.',
    privacy: 'All processing happened in your browser - no data was sent to any server.'
  };
  
  const formatSize = (bytes) => {
    if (bytes < 1024) return bytes + ' B';
    if (bytes < 1024 * 1024) return (bytes / 1024).toFixed(1) + ' KB';
    return (bytes / (1024 * 1024)).toFixed(2) + ' MB';
  };
  
  let report = `
╔══════════════════════════════════════════════════════════════╗
║                    ${labels.title}                    ║
╚══════════════════════════════════════════════════════════════╝

${labels.date}: ${new Date(reportData.timestamp).toLocaleString()}
${labels.status}: ${reportData.cleaningStatus === 'SUCCESS' ? labels.success : labels.partial}

────────────────────────────────────────────────────────────────
                         DOSYA BİLGİLERİ
────────────────────────────────────────────────────────────────
${labels.filename}: ${reportData.filename}
${labels.fileType}: ${reportData.fileType.toUpperCase()}
${labels.originalSize}: ${formatSize(reportData.originalSize)}
${labels.cleanedSize}: ${formatSize(reportData.cleanedSize)}
${labels.riskScore}: ${reportData.riskScore?.score || 0}% (${reportData.riskScore?.level || 'low'})

`;

  if (reportData.gpsRemoved && reportData.gpsCoords) {
    report += `────────────────────────────────────────────────────────────────
                       GPS VERİSİ KALDIRILDI
────────────────────────────────────────────────────────────────
⚠️  ${labels.gpsRemoved}: KALDIRILDI
    Lat: ${reportData.gpsCoords.lat.toFixed(6)}
    Lon: ${reportData.gpsCoords.lon.toFixed(6)}

`;
  }

  report += `────────────────────────────────────────────────────────────────
                       ${labels.removedData}
────────────────────────────────────────────────────────────────
`;

  if (reportData.removedItems.length > 0) {
    reportData.removedItems.forEach((item, i) => {
      const riskIcon = item.risk === 'critical' ? '🔴' : item.risk === 'high' ? '🟠' : '🟡';
      report += `${i + 1}. ${riskIcon} ${item.name}: ${item.value}\n`;
    });
  } else {
    report += `${labels.noData}\n`;
  }

  report += `
────────────────────────────────────────────────────────────────
Toplam Kaldırılan: ${reportData.totalRemoved} adet metadata
────────────────────────────────────────────────────────────────

${labels.footer}
${labels.privacy}

🔒 MetaSafe - https://metasafe.app
`;

  return report;
}

/**
 * Download report as TXT file
 * @param {Object} reportData - Report data
 * @param {string} lang - Language code
 */
function downloadTXTReport(reportData, lang = 'tr') {
  const content = generateTXTReport(reportData, lang);
  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  
  const filename = `metasafe-report-${reportData.filename.replace(/\.[^/.]+$/, '')}-${Date.now()}.txt`;
  
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
  
  return filename;
}

/**
 * Generate JSON report for programmatic use
 * @param {Object} reportData - Report data
 * @returns {string} JSON string
 */
function generateJSONReport(reportData) {
  return JSON.stringify({
    version: '1.0',
    generator: 'MetaSafe',
    ...reportData
  }, null, 2);
}

/**
 * Download report as JSON file
 * @param {Object} reportData - Report data
 */
function downloadJSONReport(reportData) {
  const content = generateJSONReport(reportData);
  const blob = new Blob([content], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  
  const filename = `metasafe-report-${reportData.filename.replace(/\.[^/.]+$/, '')}-${Date.now()}.json`;
  
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
  
  return filename;
}

// Export functions
export {
  generateReportData,
  generateTXTReport,
  downloadTXTReport,
  generateJSONReport,
  downloadJSONReport
};

// Global access
window.downloadTXTReport = downloadTXTReport;
window.downloadJSONReport = downloadJSONReport;
